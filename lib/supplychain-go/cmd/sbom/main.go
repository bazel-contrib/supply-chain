package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"sort"
	"strings"

	supplychain "github.com/bazel-contrib/supply-chain/lib/supplychain-go"
	"github.com/bazel-contrib/supply-chain/lib/supplychain-go/internal/sbom"
)

func main() {
	var inputPath, outputPath string
	var allowMissingRootMetadata, strictComponentTypes bool
	flag.StringVar(&inputPath, "input", "", "Path to graph-only JSON from gather_metadata")
	flag.StringVar(&outputPath, "output", "", "Path to write SBOM classifications")
	flag.BoolVar(&allowMissingRootMetadata, "allow_missing_root_metadata", false, "Allow SBOM generation even if root target has no metadata")
	flag.BoolVar(&strictComponentTypes, "strict_component_types", false, "Fail if the metadata of a component does not declare a component_type attribute")
	flag.Parse()

	if inputPath == "" || outputPath == "" {
		fmt.Fprintln(os.Stderr, "Error: --input and --output flags are required")
		flag.Usage()
		os.Exit(1)
	}

	inputBytes, err := os.ReadFile(inputPath)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error reading input file: %v\n", err)
		os.Exit(1)
	}

	var graphConfig sbom.GraphConfig
	if err := json.Unmarshal(inputBytes, &graphConfig); err != nil {
		fmt.Fprintf(os.Stderr, "Error parsing graph JSON: %v\n", err)
		os.Exit(1)
	}

	classifications, err := sbom.ComputeClassifications(graphConfig, allowMissingRootMetadata)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error: %v\n", err)
		os.Exit(1)
	}

	if strictComponentTypes {
		if err := checkComponentTypes(classifications); err != nil {
			fmt.Fprintf(os.Stderr, "Error: %v\n", err)
			os.Exit(1)
		}
	}

	outputBytes, err := json.MarshalIndent(classifications, "", "  ")
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error encoding classifications: %v\n", err)
		os.Exit(1)
	}

	if err := os.WriteFile(outputPath, outputBytes, 0644); err != nil {
		fmt.Fprintf(os.Stderr, "Error writing output file: %v\n", err)
		os.Exit(1)
	}
}

// checkComponentTypes fails if the metadata of a component does not declare a
// component type. The metadata files can be generated by actions, so this can
// only be checked when running.
func checkComponentTypes(classifications sbom.Classifications) error {
	nodes := append(append([]sbom.NodeConfig{}, classifications.Dependencies.Direct...), classifications.Dependencies.Transitive...)
	if classifications.RootComponent != nil {
		nodes = append(nodes, *classifications.RootComponent)
	}
	var untyped []string
	for _, node := range nodes {
		if node.MetadataFile == "" {
			continue
		}
		m, err := supplychain.ReadPackageMetadataFromFile(node.MetadataFile)
		if err != nil {
			return fmt.Errorf("error reading metadata file %s: %w", node.MetadataFile, err)
		}
		declared := false
		for _, kind := range m.ListAttributeKinds() {
			if kind == supplychain.ComponentTypeAttributeKind {
				declared = true
			}
		}
		if !declared {
			untyped = append(untyped, node.Label)
		}
	}
	if len(untyped) > 0 {
		sort.Strings(untyped)
		return fmt.Errorf("--//sbom:strict_component_types is set, but these components do not declare a component_type attribute: %s", strings.Join(untyped, ", "))
	}
	return nil
}
