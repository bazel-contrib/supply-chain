#!/usr/bin/env python3

"""Tool for updating the list of SPDX licenses and exceptions."""

import argparse
import json
import os
import sys
import xml.etree.ElementTree as ET

from typing import List


_NS = {"s": "http://www.spdx.org/license"}


def _deprecation(xml_dir: str, identifier: str, is_exception: bool, version: str) -> str:
    """Returns the deprecation message of an SPDX identifier."""
    path = os.path.join(
        xml_dir, "src", "exceptions" if is_exception else "", f"{identifier}.xml"
    )
    element = ET.parse(path).getroot()[0]
    since = element.get("deprecatedVersion")
    message = (
        f"Deprecated since SPDX license list {since}"
        if since
        else f"Deprecated in SPDX license list {version}"
    )
    replacements = []
    for obsoleted_by in element.findall("s:obsoletedBys/s:obsoletedBy", _NS):
        replacement = obsoleted_by.text.strip()
        expression = obsoleted_by.get("expression")
        replacements.append(f"{replacement} ({expression})" if expression else replacement)
    if replacements:
        message += f"; use {' or '.join(replacements)} instead"
    return message + "."


def _run(args) -> int:
    lc_all = os.environ.get("LC_ALL")
    if lc_all != "en_US.UTF-8":
        print("Your environment settings will reorder the file badly.")
        print("Please rerun as:")
        print('  LC_ALL="en_US.UTF-8"', " ".join(sys.argv))
        return 0

    with open(args.input, encoding="utf-8") as f:
        licenses_data = json.load(f)
    with open(args.exceptions, encoding="utf-8") as f:
        exceptions_data = json.load(f)

    version = licenses_data["licenseListVersion"]
    if exceptions_data["licenseListVersion"] != version:
        print("The licenses and exceptions lists have different versions.", file=sys.stderr)
        return 1

    entries = []
    for license in licenses_data["licenses"]:
        entries.append(
            (
                license["licenseId"].lower(),
                license["licenseId"],
                license["name"],
                license.get("isDeprecatedLicenseId", False),
                False,
            )
        )
    for exception in exceptions_data["exceptions"]:
        identifier = exception["licenseExceptionId"]
        entries.append(
            (
                identifier.lower(),
                identifier,
                exception["name"],
                exception.get("isDeprecatedLicenseId", False),
                True,
            )
        )

    entries_by_key = {}
    for entry in entries:
        key = entry[0]
        if key in entries_by_key:
            print(
                "Duplicate SPDX identifiers after lowercasing: "
                f"{entries_by_key[key][1]} and {entry[1]}",
                file=sys.stderr,
            )
            return 1
        entries_by_key[key] = entry

    licenses = {}
    exceptions = {}
    for key in sorted(entries_by_key):
        _, identifier, name, deprecated, is_exception = entries_by_key[key]
        data = {"identifier": identifier, "name": name}
        if deprecated:
            data["deprecation"] = _deprecation(
                args.xml_dir, identifier, is_exception, version
            )
        (exceptions if is_exception else licenses)[key] = data

    with open(args.output, "w", encoding="utf-8") as f:
        f.write(
            f"""# Generated by maintainers/tools/update_spdx_list/main.py. DO NOT EDIT.

\"\"\"The SPDX license and exception lists, the source of truth for `//licenses/spdx`.\"\"\"

visibility("//licenses/...")

# The version of the SPDX license list.
VERSION = {json.dumps(version, ensure_ascii=False)}

# Maps the lower case form of each SPDX license identifier to its data.
LICENSES = {{
"""
        )
        for key, data in licenses.items():
            f.write(f"    {json.dumps(key, ensure_ascii=False)}: {json.dumps(data, ensure_ascii=False)},\n")
        f.write("}\n\n# Maps the lower case form of each SPDX exception identifier to its data.\nEXCEPTIONS = {\n")
        for key, data in exceptions.items():
            f.write(f"    {json.dumps(key, ensure_ascii=False)}: {json.dumps(data, ensure_ascii=False)},\n")
        f.write("}\n")

    return 0


def main(argv: List[str]) -> int:
    """Main program.

    Args:
      argv: command-line arguments, such as sys.argv (including the program name
      in argv[0]).

    Returns:
      Zero on successful program termination, non-zero otherwise.
    """

    parser = argparse.ArgumentParser(description="Update SPDX license list.")
    parser.add_argument(
        "--input",
        required=True,
        help="The JSON file containing all SPDX licenses. Download from https://raw.githubusercontent.com/spdx/license-list-data/main/json/licenses.json",
    )
    parser.add_argument(
        "--exceptions",
        required=True,
        help="The JSON file containing all SPDX license exceptions, of the same version as --input. Download from https://raw.githubusercontent.com/spdx/license-list-data/main/json/exceptions.json",
    )
    parser.add_argument(
        "--xml-dir",
        required=True,
        help="A checkout of https://github.com/spdx/license-list-XML at the tag of the same version as --input (provides deprecation versions and replacements).",
    )
    parser.add_argument(
        "--output",
        required=True,
        help="The .bzl file to write the licenses and exceptions to.",
    )
    return _run(parser.parse_args(argv[1:]))


if __name__ == "__main__":
    sys.exit(main(sys.argv))
