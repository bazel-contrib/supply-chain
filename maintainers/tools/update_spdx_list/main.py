#!/usr/bin/env python3

"""Tool for updating the list of SPDX licenses."""

import argparse
import json
import os
import sys

from typing import List


def _run(args) -> int:
    lc_all = os.environ.get("LC_ALL")
    if lc_all != "en_US.UTF-8":
        print("Your environment settings will reorder the file badly.")
        print("Please rerun as:")
        print('  LC_ALL="en_US.UTF-8"', " ".join(sys.argv))
        return 0

    with open(args.input, encoding="utf-8") as f:
        licenses = json.load(f)

    licenses_by_key = {}
    for license in licenses["licenses"]:
        key = license["licenseId"].lower()
        if key in licenses_by_key:
            print(
                "Duplicate SPDX license identifiers after lowercasing: "
                f"{licenses_by_key[key]['licenseId']} and {license['licenseId']}",
                file=sys.stderr,
            )
            return 1
        licenses_by_key[key] = license

    with open(args.output, "w", encoding="utf-8") as f:
        f.write(
            f"""# Generated by maintainers/tools/update_spdx_list/main.py. DO NOT EDIT.

\"\"\"The SPDX license list, the single source of truth for `//licenses/spdx`.\"\"\"

visibility("//licenses/...")

# The version of the SPDX license list.
VERSION = {json.dumps(licenses["licenseListVersion"], ensure_ascii=False)}

# Maps the lower case form of the identifier of each SPDX license to its data.
LICENSES = {{
"""
        )
        for key in sorted(licenses_by_key):
            license = licenses_by_key[key]
            f.write(
                f"    {json.dumps(key, ensure_ascii=False)}: "
                f"{{\"identifier\": {json.dumps(license['licenseId'], ensure_ascii=False)}, "
                f"\"name\": {json.dumps(license['name'], ensure_ascii=False)}}},\n"
            )
        f.write("}\n")

    return 0


def main(argv: List[str]) -> int:
    """Main program.

    Args:
      argv: command-line arguments, such as sys.argv (including the program name
      in argv[0]).

    Returns:
      Zero on successful program termination, non-zero otherwise.
    """

    parser = argparse.ArgumentParser(description="Update SPDX license list.")
    parser.add_argument(
        "--input",
        required=True,
        help="The JSON file containing all SPDX licenses. Download from https://raw.githubusercontent.com/spdx/license-list-data/main/json/licenses.json",
    )
    parser.add_argument(
        "--output", required=True, help="The .bzl file to write the licenses to."
    )

    return _run(parser.parse_args(argv[1:]))


if __name__ == "__main__":
    sys.exit(main(sys.argv))
