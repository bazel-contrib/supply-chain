#!/usr/bin/env python3

"""Tool for updating the list of SPDX licenses."""

import argparse
import json
import os
import sys

from typing import List


def _run(args) -> int:
    lc_all = os.environ.get("LC_ALL")
    if lc_all != "en_US.UTF-8":
        print("Your environment settings will reorder the file badly.")
        print("Please rerun as:")
        print('  LC_ALL="en_US.UTF-8"', " ".join(sys.argv))
        return 0

    with open(args.input) as f:
        licenses = json.load(f)

    exceptions = []
    if args.exceptions:
        with open(args.exceptions) as f:
            exceptions_list = json.load(f)
        if exceptions_list["licenseListVersion"] != licenses["licenseListVersion"]:
            print("The licenses and exceptions lists have different versions.")
            return 1
        exceptions = [
            (
                e["licenseExceptionId"],
                e["name"],
                e.get("isDeprecatedLicenseId", False),
                True,
            )
            for e in exceptions_list["exceptions"]
        ]

    entries = [
        (l["licenseId"], l["name"], l.get("isDeprecatedLicenseId", False), False)
        for l in licenses["licenses"]
    ] + exceptions
    ids = [entry[0] for entry in entries]
    duplicates = sorted({i for i in ids if ids.count(i) > 1})
    if duplicates:
        print(f"Identifiers used by both a license and an exception: {duplicates}")
        return 1

    with open(args.output, "w") as f:
        f.write(
            f"""
# Generated by maintainers/tools/update_spdx_list/main.py. DO NOT EDIT.
#
# version: {licenses["licenseListVersion"]}

load("//licenses/rules:license_kind.bzl", "license_kind")

exports_files(
    ["ids.bzl"],
    visibility = ["//visibility:public"],
)
""".strip()
        )

        for license_id, license_name, deprecated, is_exception in sorted(entries):
            identifier = license_id.replace('"', '\\"')
            full_name = license_name.replace('"', '\\"')

            flags = ""
            if deprecated:
                flags += "\n    deprecated = True,"
            if is_exception:
                flags += "\n    exception = True,"

            f.write("\n")
            f.write("\n")
            f.write(
                f"""
license_kind(
    name = "{identifier}",{flags}
    full_name = "{full_name}",
    identifier = "{identifier}",
    visibility = ["//visibility:public"],
)
""".strip()
            )

        f.write("\n")

    if args.ids_output:
        # SPDX matches identifiers case-insensitively, so this maps the lower
        # case form of each identifier to its canonical spelling.
        with open(args.ids_output, "w") as f:
            f.write(
                f"""# Generated by maintainers/tools/update_spdx_list/main.py. DO NOT EDIT.
#
# version: {licenses["licenseListVersion"]}

\"\"\"SPDX license and exception identifiers.\"\"\"

visibility("//licenses/...")

# Maps the lower case form of each identifier to its canonical spelling.
SPDX_IDS = {{
"""
            )
            for license_id in sorted(ids):
                f.write(f'    "{license_id.lower()}": "{license_id}",\n')
            f.write("}\n")

    return 0


def main(argv: List[str]) -> int:
    """Main program.

    Args:
      argv: command-line arguments, such as sys.argv (including the program name
      in argv[0]).

    Returns:
      Zero on successful program termination, non-zero otherwise.
    """

    parser = argparse.ArgumentParser(description="Update SPDX license list.")
    parser.add_argument(
        "--input",
        required=True,
        help="The JSON file containing all SPDX licenses. Download from https://raw.githubusercontent.com/spdx/license-list-data/main/json/licenses.json",
    )
    parser.add_argument(
        "--exceptions",
        help="The JSON file containing all SPDX license exceptions, of the same version as --input. Download from https://raw.githubusercontent.com/spdx/license-list-data/main/json/exceptions.json",
    )
    parser.add_argument(
        "--output", required=True, help="The BUILD file writing targets to."
    )
    parser.add_argument(
        "--ids-output",
        help="The .bzl file writing the table of canonical identifiers to.",
    )
    return _run(parser.parse_args(argv[1:]))


if __name__ == "__main__":
    sys.exit(main(sys.argv))
